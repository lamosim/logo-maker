"""Generate the knowledge base's two data-driven pages, so the skill and the code read one source:

- .claude/skills/logo/reference/cliches.md from assets/cliches.json, which the audit's cliché check reads;
- .claude/skills/logo/reference/fonts.md from assets/fonts/catalog.json, which `logomaker fonts list` reads: its
  "Catalogue by category" section is generated and filled into scripts/templates/fonts.md, the hand-written rest.

Edit the JSON or the template, never the pages, then run: uv run python scripts/build_reference.py
tests/test_knowledge.py fails while either page differs from what this script renders.
"""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REFERENCE = ROOT / ".claude" / "skills" / "logo" / "reference"
CLICHES = ROOT / "assets" / "cliches.json"
CATALOG = ROOT / "assets" / "fonts" / "catalog.json"
FONTS_TEMPLATE = ROOT / "scripts" / "templates" / "fonts.md"
CATALOGUE_MARKER = "<!-- catalogue: generated by scripts/build_reference.py -->"
APACHE_MARKER = "<!-- apache families: generated by scripts/build_reference.py -->"

CLICHES_HEAD = """# Cliché blacklist

Read this when: writing the category audit in strategy, striking ideas in concepts/ideas.md, checking a motif the owner asks for, \
or justifying a twisted motif.

This page is generated from `assets/cliches.json` by `scripts/build_reference.py`. The audit reads the same JSON, so edit the \
JSON and re-run `uv run python scripts/build_reference.py`; never edit this page by hand.

A motif on this list is famous but not unique: it signals the category, not the brand [05 §3.3]. Use one only when the brief \
makes it the strategy, and then twist it until it scores as unique against the five nearest competitors [05 §5.5]. The AI-era \
cliché (hexagons, sparkles, concentric apertures, blue-violet gradients), with its evidence and what to reach for instead, is in \
`trends.md` under "The AI-era cliche" [05 §1.3].

## How the audit reads this list

- The audit's `cliche` check compares every entry of `META.motifs` with the Any category motifs and with the motifs of each \
industry the brand resolves to [code].
- The industry tag is brand.json's `industry` (`uv run logomaker brand set <slug> --industry "<tag>"`), else brief.json's \
`industry`. Every industry whose key or alias appears in the tag as whole words counts. The audit's `industry` info line names \
them, or says that none matched and only the Any category list was used [code].
- Terms match as whole words, so "key" does not find "keystone"; a term of three or more letters also matches its plural with \
-s or -es, so "hexagon" finds "hexagons" [code].
- A match is a warning that names the term, never a failure. Address it in critique.md: twist and justify it, or kill the \
idea [spec §8.1].
- Styles are not checked by the audit. Check them yourself against the territory's palette and the wordmark's typeface [code].
- The check only sees what `META.motifs` says, so name each motif plainly: "hexagon", not "six-sided cell".
"""

BY_INDUSTRY_NOTE = "Each heading is an industry key. Any of its aliases, or the key itself, in the brand's industry tag selects it."

CLICHES_TAIL = """## How to twist a justified motif

1. Name the category cue in one sentence, and the one idea the mark must carry instead [05 §5.5].
2. Change its construction logic, not its decoration: cut it from the name's letterform, build it from the product's real \
geometry, or make it the negative space of something ownable [05 §3.6, §5.1].
3. Remove every neighbour it usually comes with: the hexagon's sparkle, the leaf's globe, the arrow's upward slant [05 §1.3, §5.5].
4. Describe it beside the five nearest competitors from the strategy's category audit; if two of them could own it, kill \
it [05 §3.3, §5.4].
5. Keep it in `META.motifs` under its plain name, so the audit's warning stays on the critique sheet, and justify it in \
critique.md [spec §8.1].
6. Record the owner's decision: `uv run logomaker brand decide <slug> --phase concepts --by user --note "kept the <motif>, \
twisted: <how>"`.

## Sources

05 §5.5 (the industry cliché blacklist, synthesised from Zillion Designs, "40 Logo Design Cliches", the LogoLounge 2025 and 2026 \
saturation notes, Fast Company's AI-hexagon data and Free Logo Design), 05 §1.3 and §1.4 (the AI-era cliché and the saturated \
list), 05 §3.3 (distinctive assets), 04 §1.2 (cliché exclusion lists in Claude logo skills), spec §8.1; code: `assets/cliches.json`, \
`audit.check_cliches` and `audit.resolve_industries`.
"""


def render_cliches(data: dict) -> str:
    """cliches.md for the blacklist `data` (assets/cliches.json): the fixed text around its Any category and industries."""
    lines = [CLICHES_HEAD, "## Any category", "", "These apply to every brand, whatever its industry.", "",
             "Motifs: " + ", ".join(data["any"]["motifs"]), "", "Styles: " + ", ".join(data["any"]["styles"]), "",
             "## By industry", "", BY_INDUSTRY_NOTE, ""]
    for key, entry in data["industries"].items():
        lines += [f"### {key}", "", "Aliases: " + (", ".join(entry.get("aliases", [])) or "none"), "",
                  "Motifs: " + ", ".join(entry["motifs"]), ""]
        if entry.get("styles"):
            lines += ["Styles: " + ", ".join(entry["styles"]), ""]
    lines.append(CLICHES_TAIL)
    return "\n".join(lines)


def english_list(items: list[str]) -> str:
    """`items` as prose: "A", "A and B", "A, B and C"; "none" when empty."""
    return " and ".join([", ".join(items[:-1]), items[-1]]) if len(items) > 1 else (items[0] if items else "none")


def render_catalogue(catalog: dict) -> str:
    """fonts.md's "Catalogue by category" section for `catalog` (assets/fonts/catalog.json): each category in file order with
    the exact string `fonts list --category` takes, the personality tags all its families share, and each family with its
    licence (when it is not the catalogue's usual one) and its own tags."""
    families = catalog["families"]
    categories = list(dict.fromkeys(f["category"] for f in families))
    licences = Counter(f["license"] for f in families)
    usual = licences.most_common(1)[0][0]
    others = sorted(set(licences) - {usual})
    lines = [
        "## Catalogue by category",
        "",
        f"{len(families)} families in {len(categories)} categories, as `logomaker fonts list` reads them from "
        "`assets/fonts/catalog.json` [03 §4.4] [code]. Pass the category exactly as its heading reads, in quotes; any other string "
        f"exits 2 and lists all {len(categories)}. Every family is {usual}" + (f" unless marked {' or '.join(others)}" if others else "")
        + ". Tags a whole category shares are listed once; a family's own tags follow its name.",
        "",
    ]
    for category in categories:
        members = [f for f in families if f["category"] == category]
        shared = [tag for tag in members[0]["personality"] if all(tag in m["personality"] for m in members)]
        names = []
        for member in members:
            notes = ([member["license"]] if member["license"] != usual else []) + [t for t in member["personality"] if t not in shared]
            names.append(member["family"] + (f" ({', '.join(notes)})" if notes else ""))
        lines += [
            f"### {category}",
            "",
            f'- List: `uv run logomaker fonts list --category "{category}"`',
            f"- Shared tags: {', '.join(shared)}",
            f"- Families ({len(members)}): {'; '.join(names)}",
            "",
        ]
    return "\n".join(lines).rstrip("\n")


def render_fonts(catalog: dict, template: str) -> str:
    """fonts.md: `template` (scripts/templates/fonts.md) with its catalogue marker replaced by render_catalogue(catalog) and its
    Apache marker by the catalogue's Apache-licensed families."""
    for marker in (CATALOGUE_MARKER, APACHE_MARKER):
        if template.count(marker) != 1:
            raise ValueError(f"the fonts template must hold {marker!r} exactly once")
    apache = english_list([f["family"] for f in catalog["families"] if f["license"] == "Apache"])
    return template.replace(CATALOGUE_MARKER, render_catalogue(catalog)).replace(APACHE_MARKER, apache)


def main() -> None:
    REFERENCE.mkdir(parents=True, exist_ok=True)
    cliches = REFERENCE / "cliches.md"
    cliches.write_text(render_cliches(json.loads(CLICHES.read_text(encoding="utf-8"))), encoding="utf-8")
    fonts = REFERENCE / "fonts.md"
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    fonts.write_text(render_fonts(catalog, FONTS_TEMPLATE.read_text(encoding="utf-8")), encoding="utf-8")
    for path in (cliches, fonts):
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
